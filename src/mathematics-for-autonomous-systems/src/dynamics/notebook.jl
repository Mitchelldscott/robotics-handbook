"""
    PlotConfig

Configuration for styling, limits, and scales.
Default values are `nothing` (allowing Plotly to auto-scale).
"""
Base.@kwdef struct PlotConfig
    # --- Global Settings ---
    title::String = "Control System Analysis"
    resolution::Tuple{Int, Int} = (1400, 800)
	vertical_spacing::Float64 = 0.15
	horizontal_spacing::Float64 = 0.1
    
    # --- Pole-Zero Map Settings ---
    pz_pole_marker::Any  = attr(symbol="x", size=10, color="red")
    pz_zero_marker::Any  = attr(symbol="circle-open", size=10, color="blue", line=attr(width=2))
    pz_xlim::Any         = nothing  # e.g., [-10, 2]
    pz_ylim::Any         = nothing  # e.g., [-5, 5]
    pz_dtick::Any        = nothing  # Tick step size

    # --- Step Response Settings ---
    step_line::Any       = attr(color="orange", width=2)
    step_t_max::Any      = nothing  # Simulation time horizon
    step_xlim::Any       = nothing
    step_ylim::Any       = nothing

    # --- Bode Plot Settings ---
    bode_mag_line::Any   = attr(color="blue", width=2)
    bode_ph_line::Any    = attr(color="green", dash="dot", width=2)
    bode_xlim::Any       = nothing
    bode_mag_lim::Any    = nothing
    bode_ph_lim::Any     = nothing

    # --- Nyquist Settings ---
    nyquist_line::Any    = attr(color="purple", width=2)
    crit_point::Any      = attr(symbol="dot", size=12, color="red")
    nyq_xlim::Any        = nothing
    nyq_ylim::Any        = nothing
end

"""
    add_pz_map!(fig, sys, config, row, col)

Adds a Pole-Zero map to the specific subplot using styles from `config`.
"""
function add_pz_map!(fig, sys::TransferFunction, config::PlotConfig, row::Int, col::Int)
    p = poles(sys)
    z = tzeros(sys)

    trace_poles = scatter(
        x=real(p), y=imag(p), 
        mode="markers", 
        marker=config.pz_pole_marker,
        name="Poles",
        legendgroup="pz"
    )
    
    trace_zeros = scatter(
        x=real(z), y=imag(z), 
        mode="markers", 
        marker=config.pz_zero_marker,
        name="Zeros",
        legendgroup="pz"
    )

    add_trace!(fig, trace_poles, row=row, col=col)
    add_trace!(fig, trace_zeros, row=row, col=col)
	update_xaxes!(fig; row=row, col=col, title="Real", xlim=config.pz_xlim)
    update_yaxes!(fig; row=row, col=col, title="Imaginary", ylim=config.pz_ylim)
end

"""
    add_step_response!(fig, sys, config, row, col)
"""
function add_step_response!(fig, sys::TransferFunction, config::PlotConfig, row::Int, col::Int)
    y, t, _ = step(sys)
    
    trace = scatter(
        x=vec(t), y=vec(y),
        mode="lines",
        line=config.step_line,
        name="Step Response"
    )

    add_trace!(fig, trace, row=row, col=col)
	update_xaxes!(fig; row=row, col=col, title="Time (s)", xlim=config.step_xlim)
    update_yaxes!(fig; row=row, col=col, title="Amplitude", ylim=config.step_ylim)
end

