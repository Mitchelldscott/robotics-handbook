"""
    analyze_system_2x2(sys::TransferFunction)

Creates a 2x2 interactive PlotlyJS chart showing:
1. Top-Left:  Pole-Zero Map
2. Top-Right: Step Response
3. Bot-Left:  Bode Plot (Dual Axis: Mag dB & Phase deg)
4. Bot-Right: Nyquist Plot
"""
function analyze_system_2x2(sys::TransferFunction)
    # --- 1. Pole-Zero Data ---
    p = poles(sys)
    z = tzeros(sys)
    
    trace_poles = scatter(
        x=real(p), y=imag(p), 
        mode="markers", marker=attr(symbol="x", size=10, color="red"),
        name="Poles"
    )
    
    trace_zeros = scatter(
        x=real(z), y=imag(z), 
        mode="markers", marker=attr(symbol="circle-open", size=10, color="blue", line=attr(width=2)),
        name="Zeros"
    )

    # --- 2. Step Response Data ---
    y_step, t_step, _ = step(sys)
    y_vec = vec(y_step)
    t_vec = vec(t_step)

    trace_step = scatter(
        x=t_vec, y=y_vec,
        mode="lines", line=attr(color="orange"),
        name="Step Response"
    )

    # --- 3. Bode Data (Mag & Phase) ---
    mag, ph, w = bode(sys)
    w_vec = vec(w)
    
    # Convert Magnitude to dB
    mag_db = 20 .* log10.(vec(mag))
    ph_vec = vec(ph)

    trace_bode_mag = scatter(
        x=w_vec, y=mag_db,
        mode="lines", line=attr(color="blue"),
        name="Magnitude (dB)"
    )

    trace_bode_ph = scatter(
        x=w_vec, y=ph_vec,
        mode="lines", line=attr(color="green", dash="dot"),
        name="Phase (deg)",
        yaxis="y3_2" # Internal plotly reference for secondary axis if needed manually, but handled by specs below
    )

    # --- 4. Nyquist Data ---
    # Reconstruct Complex numbers from Bode data (mag/phase)
    # Real = mag * cos(ph_rad), Imag = mag * sin(ph_rad)
    ph_rad = deg2rad.(ph_vec)
    re_nyq = vec(mag) .* cos.(ph_rad)
    im_nyq = vec(mag) .* sin.(ph_rad)

    trace_nyquist = scatter(
        x=re_nyq, y=im_nyq,
        mode="lines", line=attr(color="purple"),
        name="Nyquist"
    )
    
    # Add Critical Point (-1, 0j) for Nyquist visual reference
    trace_critical = scatter(
        x=[-1], y=[0],
        mode="markers", marker=attr(symbol="cross", size=10, color="red"),
        showlegend=false, hoverinfo="skip"
    )

    # --- Layout & Subplots ---
    fig = make_subplots(
        rows=2, cols=2,
        subplot_titles=["Pole-Zero Map" "Step Response" "Bode Plot" "Nyquist Plot"],
        specs=[
            Spec()                   Spec();
            Spec(secondary_y=true)   Spec()
        ],
        vertical_spacing=0.15,
        horizontal_spacing=0.1
    )

    # (1,1) Pole-Zero
    add_trace!(fig, trace_poles, row=1, col=1)
    add_trace!(fig, trace_zeros, row=1, col=1)

    # (1,2) Step Response
    add_trace!(fig, trace_step, row=1, col=2)

    # (2,1) Bode (Mag on Primary Y, Phase on Secondary Y)
    add_trace!(fig, trace_bode_mag, row=2, col=1, secondary_y=false)
    add_trace!(fig, trace_bode_ph, row=2, col=1, secondary_y=true)

    # (2,2) Nyquist
    add_trace!(fig, trace_nyquist, row=2, col=2)
    add_trace!(fig, trace_critical, row=2, col=2)

    # --- Final Styling & Units ---
    relayout!(fig, 
        title_text="System Analysis (2x2)",
        height=700, width=900,
        showlegend=true
    )

    # 1. Pole-Zero Styling
    update_xaxes!(fig, title_text="Real", row=1, col=1, zeroline=true)
    update_yaxes!(fig, title_text="Imaginary", row=1, col=1, zeroline=true)

    # 2. Step Response Styling
    update_xaxes!(fig, title_text="Time (s)", row=1, col=2)
    update_yaxes!(fig, title_text="Amplitude", row=1, col=2)

    # 3. Bode Styling
    update_xaxes!(fig, title_text="Frequency (rad/s)", type="log", row=2, col=1)
    update_yaxes!(fig, title_text="Magnitude (dB)", color="blue", row=2, col=1, secondary_y=false)
    update_yaxes!(fig, title_text="Phase (deg)", color="green", row=2, col=1, secondary_y=true, showgrid=false)

    # 4. Nyquist Styling
    update_xaxes!(fig, title_text="Real Axis", row=2, col=2, zeroline=true)
    update_yaxes!(fig, title_text="Imaginary Axis", row=2, col=2, zeroline=true)

    return fig
end

