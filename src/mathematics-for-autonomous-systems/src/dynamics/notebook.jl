"""
    analyze_system(sys::TransferFunction)

Creates a 1x3 interactive PlotlyJS chart showing:
1. Pole-Zero Map
2. Bode Phase Plot
3. Step Response
"""
function analyze_system(sys::TransferFunction)
    # --- 1. Pole-Zero Map Data ---
    p = poles(sys)
    z = tzeros(sys)
    
    trace_poles = scatter(
        x=real(p), y=imag(p), 
        mode="markers", marker=attr(symbol="x", size=10, color="red"),
        name="Poles"
    )
    
    trace_zeros = scatter(
        x=real(z), y=imag(z), 
        mode="markers", marker=attr(symbol="circle-open", size=10, color="blue", line=attr(width=2)),
        name="Zeros"
    )

    # --- 2. Phase Plot Data (Bode) ---
    # bode returns (mag, phase_deg, w)
    mag, ph, w = bode(sys)
    
    # Flatten arrays for plotting (ControlSystems returns 3D arrays for MIMO, we assume SISO here)
    w_vec = vec(w)
    ph_vec = vec(ph)

    trace_phase = scatter(
        x=w_vec, y=ph_vec,
        mode="lines", line=attr(color="green"),
        name="Phase"
    )

    # --- 3. Time Response Data (Step) ---
    y, t, x = step(sys)
    y_vec = vec(y)
    t_vec = vec(t)

    trace_step = scatter(
        x=t_vec, y=y_vec,
        mode="lines", line=attr(color="orange"),
        name="Step Response"
    )

    # --- Layout & Subplots ---
    fig = make_subplots(
        rows=1, cols=3,
        subplot_titles=["Pole-Zero Map" "Bode Phase Plot" "Step Response"]
    )

    # Add Pole-Zero traces
    add_trace!(fig, trace_poles, row=1, col=1)
    add_trace!(fig, trace_zeros, row=1, col=1)

    # Add Phase trace
    add_trace!(fig, trace_phase, row=1, col=2)

    # Add Step trace
    add_trace!(fig, trace_step, row=1, col=3)

    # --- Final Layout Adjustments ---
    relayout!(fig, 
	    title_text="System Analysis",
	    showlegend=true,
	    height=500
	)

    # Axis Labels
    # Plot 1: PZ Map
    update_xaxes!(fig, title_text="Real", row=1, col=1, zeroline=true, zerolinewidth=2)
    update_yaxes!(fig, title_text="Imaginary", row=1, col=1, zeroline=true, zerolinewidth=2)

    # Plot 2: Phase (Log X axis)
    update_xaxes!(fig, title_text="Frequency (rad/s)", type="log", row=1, col=2)
    update_yaxes!(fig, title_text="Phase (deg)", row=1, col=2)

    # Plot 3: Step
    update_xaxes!(fig, title_text="Time (s)", row=1, col=3)
    update_yaxes!(fig, title_text="Amplitude", row=1, col=3)

    return fig
end

