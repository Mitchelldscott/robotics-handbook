"""
    add_nyquist_plot!(fig, sys, config, row, col)
"""
function add_nyquist_plot!(fig, sys::TransferFunction, config::PlotConfig, row::Int, col::Int)
    mag, ph, _ = bode(sys)
    ph_rad = deg2rad.(vec(ph))
    re = vec(mag) .* cos.(ph_rad)
    im = vec(mag) .* sin.(ph_rad)

    trace_nyq = scatter(
        x=re, y=im,
        mode="lines", line=config.nyquist_line,
        name="Nyquist"
    )
    
    trace_crit = scatter(
        x=[-1], y=[0],
        mode="markers", marker=config.crit_point,
        showlegend=false, hoverinfo="skip"
    )

    add_trace!(fig, trace_nyq, row=row, col=col)
    add_trace!(fig, trace_crit, row=row, col=col)
	update_xaxes!(fig; row=row, col=col, title="Real", range=config.nyq_xlim)
    update_yaxes!(fig; row=row, col=col, title="Imaginary", range=config.nyq_ylim)
end


"""
    build_dashboard(sys, config=PlotConfig())

Main entry point. Assembles the dashboard.
"""
function build_dashboard(sys::TransferFunction; config::PlotConfig=PlotConfig())
    specs_matrix = [
        Spec()    Spec();
        Spec()    Spec(rowspan=2);
        Spec()    missing
    ]

    fig = make_subplots(
        rows=3, cols=2,
        subplot_titles=["Pole-Zero Map" "Step Response" "Bode Magnitude" "Nyquist Plot" "Bode Phase"],
        specs=specs_matrix,
        vertical_spacing=config.vertical_spacing, horizontal_spacing=config.horizontal_spacing
    )

    # Call the helper functions (dispatching on config)
    ControlViz.add_pz_map!(fig, sys, config, 1, 1)
    ControlViz.add_step_response!(fig, sys, config, 1, 2)
    ControlViz.add_bode_plot!(fig, sys, config, 2, 1)
    ControlViz.add_nyquist_plot!(fig, sys, config, 2, 2)

    # Apply global layout settings
    relayout!(fig, 
        title=config.title,
        width=config.resolution[1], 
        height=config.resolution[2],
        template="plotly_dark"
    )
    
    return fig
end

